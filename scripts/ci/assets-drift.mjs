// Drift check of the shipped stuffcloud pixel art (#56).
//
// The art is drawn in the stuffcloud repository (docs/design/prototypes, generated from ASCII
// sources by docs/design/tools/mascots.py and stickers.py); kern ships byte-identical copies under
// assets/stuffcloud/<group>/. CI cannot reach the stuffcloud repository, so the checked-in manifest
// assets/stuffcloud/manifest.json is the contract: every file with its size, sha256 and pixel grid.
//
// Usage:
//   node scripts/ci/assets-drift.mjs                    check assets/stuffcloud against the manifest
//                                                       and the generated catalogue (CI, `build` job)
//   node scripts/ci/assets-drift.mjs --write            rewrite the manifest and the catalogue
//                                                       (src/lib/components/stuffcloud-art.ts) from the tree
//   node scripts/ci/assets-drift.mjs --against <dir>    also compare names and bytes with a stuffcloud
//                                                       checkout's docs/design/prototypes folder
//                                                       (usable from stuffcloud's CI with a kern checkout)
// Exit code 1 on any drift: a missing, extra or changed file.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const artDir = join(root, 'assets', 'stuffcloud');
const manifestFile = join(artDir, 'manifest.json');
const catalogueFile = join(root, 'src', 'lib', 'components', 'stuffcloud-art.ts');
const SOURCE = 'Mozra-the-great/stuffcloud docs/design/prototypes';

const args = process.argv.slice(2);
const write = args.includes('--write');
const againstAt = args.indexOf('--against');
const against = againstAt === -1 ? undefined : args[againstAt + 1];
if (againstAt !== -1 && (against === undefined || against.startsWith('--'))) {
	console.error('--against needs the path of a stuffcloud docs/design/prototypes folder');
	process.exit(2);
}

/** Every file under assets/stuffcloud except the manifest itself, as posix paths relative to it. */
function listTree(dir, prefix = '') {
	const out = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
		if (entry.isDirectory()) out.push(...listTree(join(dir, entry.name), rel));
		else if (rel !== 'manifest.json') out.push(rel);
	}
	return out.sort();
}

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/** The pixel grid of a stuffcloud SVG: its integer viewBox `0 0 cols rows`. */
function gridOf(buf) {
	const m = /viewBox="0 0 (\d+) (\d+)"/.exec(buf.toString('utf8'));
	return m ? { cols: Number(m[1]), rows: Number(m[2]) } : undefined;
}

function describeTree() {
	const files = {};
	const gridless = [];
	for (const rel of listTree(artDir)) {
		const buf = readFileSync(join(artDir, rel));
		const grid = rel.endsWith('.svg') ? gridOf(buf) : undefined;
		if (rel.endsWith('.svg') && !grid) gridless.push(`${rel}: no integer viewBox "0 0 <cols> <rows>" (pixel art needs one)`);
		files[rel] = { bytes: buf.length, sha256: sha256(buf), ...grid };
	}
	return { files, gridless };
}

function manifestText(files) {
	const manifest = {
		$comment: 'Generated by `npm run assets:manifest` (scripts/ci/assets-drift.mjs --write). Do not edit by hand; see assets/README.md.',
		source: SOURCE,
		files
	};
	return JSON.stringify(manifest, null, '\t') + '\n';
}

function catalogueText(files) {
	const lines = Object.entries(files)
		.filter(([rel]) => rel.endsWith('.svg'))
		.map(([rel, f]) => `\t'${rel.replace(/\.svg$/, '')}': { cols: ${f.cols}, rows: ${f.rows} },`);
	return [
		'// Generated by `npm run assets:manifest` (scripts/ci/assets-drift.mjs --write) from',
		'// assets/stuffcloud. Do not edit by hand: change the art, then regenerate.',
		'',
		'/** Size of a piece of pixel art in art pixels (the integer `viewBox` of its SVG). */',
		'export interface PixelGrid {',
		'\treadonly cols: number;',
		'\treadonly rows: number;',
		'}',
		'',
		'/** Every shipped stuffcloud SVG, keyed `<group>/<file>` (path under `assets/stuffcloud/`, without `.svg`). */',
		'export const STUFFCLOUD_ART = {',
		...lines,
		'} as const satisfies Readonly<Record<string, PixelGrid>>;',
		'',
		'/** Path of a shipped stuffcloud SVG under `assets/stuffcloud/`, without `.svg`, e.g. `mascots/axo`. */',
		'export type StuffcloudArt = keyof typeof STUFFCLOUD_ART;',
		''
	].join('\n');
}

const { files, gridless } = describeTree();
const problems = [...gridless];

if (write && gridless.length > 0) {
	console.error(`Not written:\n  ${gridless.join('\n  ')}`);
	process.exit(1);
} else if (write) {
	writeFileSync(manifestFile, manifestText(files));
	writeFileSync(catalogueFile, catalogueText(files));
	console.log(`Wrote ${relative(root, manifestFile)} and ${relative(root, catalogueFile)} (${Object.keys(files).length} files).`);
} else {
	// 1. Tree against the manifest.
	let expected = {};
	try {
		expected = JSON.parse(readFileSync(manifestFile, 'utf8')).files ?? {};
	} catch (e) {
		problems.push(`cannot read ${relative(root, manifestFile)}: ${e.message}`);
	}
	for (const rel of Object.keys(expected))
		if (!(rel in files)) problems.push(`missing: ${rel} (listed in the manifest, not in assets/stuffcloud)`);
	for (const [rel, f] of Object.entries(files)) {
		const want = expected[rel];
		if (!want) problems.push(`extra: ${rel} (in assets/stuffcloud, not in the manifest)`);
		else if (want.sha256 !== f.sha256 || want.bytes !== f.bytes)
			problems.push(
				`changed: ${rel} (${f.bytes} bytes, sha256 ${f.sha256.slice(0, 12)}…; manifest: ${want.bytes} bytes, ${String(want.sha256).slice(0, 12)}…)`
			);
		else if (want.cols !== f.cols || want.rows !== f.rows) problems.push(`changed grid: ${rel}`);
	}
	// 2. Catalogue (src/lib/components/stuffcloud-art.ts) against the tree. Parsed loosely, so a
	// formatter may restyle the generated file without failing the check.
	const catalogue = existsSync(catalogueFile) ? readFileSync(catalogueFile, 'utf8') : '';
	const listed = new Map(
		[...catalogue.matchAll(/['"]([\w/-]+)['"]\s*:\s*\{\s*cols:\s*(\d+),\s*rows:\s*(\d+)\s*,?\s*\}/g)].map((m) => [
			m[1],
			{ cols: Number(m[2]), rows: Number(m[3]) }
		])
	);
	const svgs = Object.entries(files).filter(([rel]) => rel.endsWith('.svg'));
	for (const [rel, f] of svgs) {
		const key = rel.replace(/\.svg$/, '');
		const got = listed.get(key);
		if (!got) problems.push(`catalogue: ${key} is missing in ${relative(root, catalogueFile)}`);
		else if (got.cols !== f.cols || got.rows !== f.rows)
			problems.push(`catalogue: ${key} is ${got.cols}x${got.rows}, the SVG is ${f.cols}x${f.rows}`);
	}
	const keys = new Set(svgs.map(([rel]) => rel.replace(/\.svg$/, '')));
	for (const key of listed.keys()) if (!keys.has(key)) problems.push(`catalogue: ${key} has no SVG`);
}

// 3. Optional: names and bytes against a stuffcloud prototypes folder (flat, *.svg).
if (against !== undefined) {
	const dir = resolve(against);
	if (!existsSync(dir) || !statSync(dir).isDirectory()) {
		problems.push(`--against: ${dir} is not a directory`);
	} else {
		const theirs = new Map(
			readdirSync(dir)
				.filter((f) => f.endsWith('.svg'))
				.map((f) => [f, join(dir, f)])
		);
		const ours = new Map();
		for (const rel of Object.keys(files).filter((r) => r.endsWith('.svg'))) {
			const name = basename(rel);
			if (ours.has(name)) problems.push(`stuffcloud: ${name} exists twice in kern (${ours.get(name)}, ${rel})`);
			ours.set(name, rel);
		}
		for (const [name, path] of theirs) {
			const rel = ours.get(name);
			if (!rel) problems.push(`stuffcloud: ${name} is not shipped by kern (copy it into the right assets/stuffcloud/<group>/)`);
			else if (sha256(readFileSync(path)) !== files[rel].sha256) problems.push(`stuffcloud: ${name} differs from kern's ${rel}`);
		}
		for (const [name, rel] of ours) if (!theirs.has(name)) problems.push(`stuffcloud: kern's ${rel} does not exist in ${dir}`);
		if (problems.length === 0) console.log(`Same ${theirs.size} SVG files (names and bytes) as ${dir}.`);
	}
}

if (problems.length > 0) {
	console.error(`Pixel-art drift (${problems.length}):\n  ${problems.join('\n  ')}`);
	console.error(
		'If the art changed on purpose: copy the files from stuffcloud, run `npm run assets:manifest`, commit (see assets/README.md).'
	);
	process.exit(1);
}
if (!write) console.log(`assets/stuffcloud matches its manifest and the catalogue (${Object.keys(files).length} files).`);
